// EXPLAIN before/after for the indexing requirement. Needs the admin account (it drops and re-creates an index).
//   npm run explain:demo        -> also writes docs/EXPLAIN_RESULTS.md
import fs from 'node:fs';
import path from 'node:path';
import mysql from 'mysql2/promise';
import { ROOT, dbConfig } from './_env.mjs';

const conn = await mysql.createConnection({ ...dbConfig(true), decimalNumbers: true });
await conn.query("SET time_zone = '+00:00'");
const md = ['# EXPLAIN results (before / after indexing)', '', `Generated by \`npm run explain:demo\` on ${new Date().toISOString().slice(0, 10)}.`, ''];
const out = (s = '') => { console.log(s); md.push(s); };

async function time(sql, params = [], runs = 30) {
  await conn.query(sql, params);                      // warm up
  const t0 = process.hrtime.bigint();
  for (let i = 0; i < runs; i++) await conn.query(sql, params);
  return Number(process.hrtime.bigint() - t0) / 1e6 / runs;
}
async function plan(sql, params = []) {
  const [rows] = await conn.query(`EXPLAIN ${sql}`, params);
  return rows.map((r) => ({ table: r.table, type: r.type, key: r.key, rows: r.rows, filtered: r.filtered, Extra: r.Extra }));
}
function show(label, p, ms) {
  out(`**${label}**  (avg ${ms.toFixed(2)} ms over 30 runs)`);
  out('');
  out('| table | type | key | rows | Extra |');
  out('|---|---|---|---|---|');
  for (const r of p) out(`| ${r.table} | ${r.type} | ${r.key ?? 'NULL'} | ${r.rows} | ${r.Extra ?? ''} |`);
  out('');
}
for (const t of ['audit_log', 'claims', 'items']) await conn.query(`ANALYZE TABLE \`${t}\``);
const [[{ n: auditRows }]] = [(await conn.query('SELECT COUNT(*) AS n FROM audit_log'))[0]];
const [[{ n: itemRows }]] = [(await conn.query('SELECT COUNT(*) AS n FROM items'))[0]];
out(`Data volume: ${auditRows} audit rows, ${itemRows} items.`);
out();

/* 1 --- add an index: audit viewer */
const actor = (await conn.query("SELECT changed_by FROM audit_log WHERE changed_by LIKE 'app:staff#%' GROUP BY changed_by ORDER BY COUNT(*) DESC LIMIT 1"))[0][0]?.changed_by ?? 'seed-script';
const q1 = `SELECT audit_id, table_name, action, changed_at FROM audit_log WHERE changed_by = ? ORDER BY changed_at DESC`;
out('## 1. CREATE INDEX: "what did this actor change recently?" (admin audit viewer)');
out();
out('```sql\n' + q1.replace('?', `'${actor}'`) + '\n```');
out();
await conn.query('DROP INDEX idx_audit_actor_time ON audit_log');
show('BEFORE - no index on changed_by', await plan(q1, [actor]), await time(q1, [actor]));
await conn.query('CREATE INDEX idx_audit_actor_time ON audit_log (changed_by, changed_at)');
show('AFTER - CREATE INDEX idx_audit_actor_time (changed_by, changed_at)', await plan(q1, [actor]), await time(q1, [actor]));

/* 2 --- index vs forced scan: fraud rule lookup */
const q2 = `SELECT COUNT(*) FROM claims WHERE claimant_id = ? AND submitted_at >= NOW() - INTERVAL 24 HOUR`;
const uid = (await conn.query('SELECT claimant_id FROM claims GROUP BY claimant_id ORDER BY COUNT(*) DESC LIMIT 1'))[0][0].claimant_id;
out('## 2. Composite index: the RAPID_CLAIMS fraud rule (runs inside a trigger on every claim)');
out();
out('```sql\n' + q2.replace('?', uid) + '\n```');
out();
const claimIdx = [...new Set((await conn.query('SHOW INDEX FROM claims'))[0].map((r) => r.Key_name))].filter((k) => k !== 'PRIMARY');
const q2ignore = q2.replace('FROM claims', `FROM claims IGNORE INDEX (${claimIdx.join(', ')})`);
show('WITHOUT the index (IGNORE INDEX)', await plan(q2ignore, [uid]), await time(q2ignore, [uid]));
show('WITH idx_claims_claimant (claimant_id, submitted_at)', await plan(q2, [uid]), await time(q2, [uid]));

/* 3 --- full-text vs LIKE */
out('## 3. FULLTEXT index vs LIKE \'%word%\'');
out();
const q3a = `SELECT item_id FROM items WHERE description LIKE '%wallet%' AND description LIKE '%black%'`;
const q3b = `SELECT item_id FROM items WHERE MATCH(title, description) AGAINST ('+wallet* +black*' IN BOOLEAN MODE)`;
out('```sql\n' + q3a + ';\n' + q3b + ';\n```');
out();
show('LIKE (cannot use any index - leading wildcard)', await plan(q3a), await time(q3a));
show('MATCH ... AGAINST (uses ft_items_text)', await plan(q3b), await time(q3b));

/* 4 --- covering index for status browse */
const q4 = `SELECT item_id, title FROM items WHERE status = 'REGISTERED' AND found_at >= NOW() - INTERVAL 30 DAY ORDER BY found_at DESC LIMIT 12`;
out('## 4. Composite index (status, found_at): the public browse page');
out();
out('```sql\n' + q4 + ';\n```');
out();
show('WITHOUT (IGNORE INDEX idx_items_status_found, idx_items_found_at)', await plan(q4.replace('FROM items', 'FROM items IGNORE INDEX (idx_items_status_found, idx_items_found_at)')), await time(q4.replace('FROM items', 'FROM items IGNORE INDEX (idx_items_status_found, idx_items_found_at)')));
show('WITH idx_items_status_found', await plan(q4), await time(q4));

fs.writeFileSync(path.join(ROOT, 'docs', 'EXPLAIN_RESULTS.md'), md.join('\n'));
console.log('Wrote docs/EXPLAIN_RESULTS.md');
await conn.end();
