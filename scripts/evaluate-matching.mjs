// Measures match quality on the labelled lost/found pairs written by the seed script.
// For each pair we ask: where does the TRUE item rank for the owner's (paraphrased, partial) description?
//   vector-only | structured-only | hybrid  (+ a sweep over the fusion weight ALPHA)
//   npm run eval:matching
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './_env.mjs';
import { hybridMatch } from '../src/lib/matching.js';
import { ensureIndexed, drainOutbox } from '../src/lib/sync.js';
import { providerName, providerTag } from '../src/lib/embeddings.js';
import { pool, query } from '../src/lib/db.js';

const file = path.join(ROOT, 'data', 'eval_pairs.json');
if (!fs.existsSync(file)) { console.error('Run "npm run db:seed" first (it writes data/eval_pairs.json).'); process.exit(1); }
const pairs = JSON.parse(fs.readFileSync(file, 'utf8'));
await drainOutbox().catch(() => {});
await ensureIndexed();

async function run(mode, alpha) {
  if (alpha !== undefined) process.env.MATCH_ALPHA = String(alpha);
  const ranks = [];
  for (const p of pairs) {
    const res = await hybridMatch(p.query, { mode, limit: 20, skipSync: true });
    const idx = res.findIndex((r) => r.item_id === p.truth_item_id);
    ranks.push(idx === -1 ? Infinity : idx + 1);
  }
  const n = ranks.length;
  const at = (k) => ranks.filter((r) => r <= k).length / n;
  const mrr = ranks.reduce((s, r) => s + (r === Infinity ? 0 : 1 / r), 0) / n;
  return { top1: at(1), top3: at(3), top5: at(5), top10: at(10), mrr };
}

const pct = (x) => `${(x * 100).toFixed(1)}%`;
const rows = [];
const baseAlpha = process.env.MATCH_ALPHA ?? '0.6';
const t0 = Date.now();
const vec = await run('vector');
const str = await run('structured');
const hyb = await run('hybrid', baseAlpha);
rows.push(['Vector only (cosine)', vec], ['Structured only (attributes)', str], [`Hybrid (alpha=${baseAlpha})`, hyb]);

const sweep = [];
for (const a of [0, 0.2, 0.4, 0.6, 0.8, 1]) sweep.push([a, await run('hybrid', a)]);
process.env.MATCH_ALPHA = baseAlpha;

const [{ open }] = await query("SELECT COUNT(*) AS open FROM items WHERE status IN ('REGISTERED','CLAIMED')");
const header = `Pairs: ${pairs.length}   searchable items in the index: ${open}   embedding: ${providerName()} (${providerTag()})`;
console.log(`\n${header}\n`);
console.table(rows.map(([name, m]) => ({ method: name, 'top-1': pct(m.top1), 'top-3': pct(m.top3), 'top-5': pct(m.top5), 'top-10': pct(m.top10), MRR: m.mrr.toFixed(3) })));
console.log('ALPHA sweep (weight of the vector score; 0 = attributes only, 1 = vector only)');
console.table(sweep.map(([a, m]) => ({ alpha: a, 'top-1': pct(m.top1), 'top-5': pct(m.top5), MRR: m.mrr.toFixed(3) })));

const md = [
  '# Matching evaluation', '',
  `Generated by \`npm run eval:matching\` on ${new Date().toISOString().slice(0, 10)}.`, '',
  `- Labelled pairs: **${pairs.length}** (each owner query is a *paraphrase* of the found-item description, with attributes randomly omitted or wrong)`,
  `- Searchable items (status REGISTERED / CLAIMED): **${open}**`,
  `- Embedding: \`${providerName()}\` (${providerTag()}), cosine similarity, fusion weight alpha = ${baseAlpha}`, '',
  '| Method | top-1 | top-3 | top-5 | top-10 | MRR |', '|---|---|---|---|---|---|',
  ...rows.map(([n, m]) => `| ${n} | ${pct(m.top1)} | ${pct(m.top3)} | ${pct(m.top5)} | ${pct(m.top10)} | ${m.mrr.toFixed(3)} |`), '',
  '## Alpha sweep', '', '| alpha | top-1 | top-5 | MRR |', '|---|---|---|---|',
  ...sweep.map(([a, m]) => `| ${a} | ${pct(m.top1)} | ${pct(m.top5)} | ${m.mrr.toFixed(3)} |`), '',
  `Runtime: ${((Date.now() - t0) / 1000).toFixed(0)} s for ${pairs.length * 9} match queries.`, '',
  '> Synthetic benchmark: found items and owner queries are generated from the same catalogue with different phrasing. ' +
  'Treat the numbers as a relative comparison of methods, not as real-world accuracy.', '',
];
fs.writeFileSync(path.join(ROOT, 'docs', 'MATCHING_EVALUATION.md'), md.join('\n'));
fs.writeFileSync(path.join(ROOT, 'data', 'eval_results.json'), JSON.stringify({ header, rows, sweep }, null, 1));
console.log('\nWrote docs/MATCHING_EVALUATION.md');
await pool().end();
